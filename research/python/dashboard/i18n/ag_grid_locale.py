def ag_grid_locale_text(locale: object) -> dict[str, str]:
    """Return a defensive copy of the requested AG Grid locale mapping."""

    resolved = normalize_locale(locale)
    source = AG_GRID_LOCALE_VI if resolved == "vi" else AG_GRID_LOCALE_EN
    return dict(source)


def validate_ag_grid_locale_parity() -> None:
    """Fail when EN and VI stop covering the same AG Grid message keys."""

    en_keys = set(AG_GRID_LOCALE_EN)
    vi_keys = set(AG_GRID_LOCALE_VI)
    if en_keys != vi_keys:
        raise RuntimeError(
            "AG Grid locale parity failed: "
            f"missing_vi={sorted(en_keys - vi_keys)}, "
            f"missing_en={sorted(vi_keys - en_keys)}"
        )
    blank = {
        locale: sorted(key for key, value in mapping.items() if not value.strip())
        for locale, mapping in {
            "en": AG_GRID_LOCALE_EN,
            "vi": AG_GRID_LOCALE_VI,
        }.items()
    }
    if any(blank.values()):
        raise RuntimeError(f"AG Grid locale contains blank values: {blank}")


